// PoAW chains as spellweb nodes (2026-10-25). Reads mages.city's chains.json (written by blake3_mage's
// levers/evidence_cards.mjs from the chain builds) and writes src/data/chains.ts: one `chain` node per chain,
// placed on the lattice by its ledger root's first six bits (Protection = 32 … Value = 1, the same order as
// agentprivacy's lib/lattice-vertex.ts), an `instance_of` edge to the PoAW-chain concept, and an `anchors_to` edge
// to its vertex node where one exists (spellweb keeps zero broken endpoints; the vertex is carried on the node
// either way). Work roots only, by Mitch's call: entry roots stay on the chain pages.
// usage: node scripts/sync-chains.mjs [path to chains.json]   (default ../mages_city/site/chains.json)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.argv[2] || path.join(ROOT, "..", "mages_city", "site", "chains.json");
const J = JSON.parse(fs.readFileSync(SRC, "utf8"));
const nodesTs = fs.readFileSync(path.join(ROOT, "src", "data", "nodes.ts"), "utf8");
const vertexIds = new Set([...nodesTs.matchAll(/id: "(vertex-v\d+)"/g)].map(m => m[1]));
const bits6 = v => v.toString(2).padStart(6, "0");
const nodes = [{
  id: "concept-poaw-chain", type: "concept", label: "PoAW chain", domain: "mage", layer: "knowledge", emoji: "⛓️",
  desc: "A proof of agentic work as a page of its own: every record of a mage instance's work, the failed tries included, addressed by the hash of its bytes and sealed under one root, re-derived in the reader's browser. Read four ways: a place on the star, a sign (hexagram), a sound (beat), a name (its seal). Lever names are the members'; the public sees kinds and hashes. A face of the evidence picks one root per vertex and folds into a City Key as `chains`, moving its κ.",
  href: "https://mages.city/arena.html#pw-chain-cards",
  evidence: { status: "local implementation", observedAt: J.generated, sources: ["mages_city/site/chains.json", "mages_city/site/star.html", "blake3_mage/levers/chain_site.py"], note: "Twelve chains built locally from κ-evidence bundles; not yet deployed." },
}, {
  id: "concept-mage-quest", type: "concept", label: "The mage's quest", domain: "mage", layer: "knowledge", emoji: "🧭",
  desc: "The mage's quest: an adventure that turns into a guide. Every problem a mage takes on is a quest with a subdomain of its own: a promise anyone can check (its PoAW chain, re-derived in the reader's browser) and a knowledge graph of what the quest learns, readable by members, until the adventure turns into a guide for the next mage.",
  href: "https://guide.agentprivacy.ai/guide/the-mages-quest.html",
  evidence: { status: "local implementation", observedAt: J.generated, sources: ["blake3_mage/docs/HONING_THE_EXPRESSION_2026-10-25_QUEST.md", "agentprivacy.guide flow/builders/vta-lane.mjs (the-mages-quest)"], note: "The line settled 2026-10-25; ten quest homes staged, not yet deployed." },
}];
// the quest is built on the chain (its promise, kept in public) and on promise theory (an agent promises only its own behaviour)
const edges = [{ source: "concept-mage-quest", target: "concept-poaw-chain", type: "built_on" }];
if (/id: "con-promisetheory"/.test(nodesTs)) edges.push({ source: "concept-mage-quest", target: "con-promisetheory", type: "built_on" });
for (const c of J.chains) {
  const hex = String(c.work_root || "").split(":").pop();
  if (!/^[0-9a-f]{64}$/.test(hex)) continue;
  const v = parseInt(hex.slice(0, 2), 16) >> 2, b = bits6(v);
  const id = "chain-" + c.id.replace(/_/g, "-");
  nodes.push({
    id, type: "chain", label: `${c.name} ⛓️`, domain: "mage", layer: "chronicle", emoji: "⛓️",
    desc: `The ${c.name} PoAW chain (${c.lane}): ${c.entries} ${c.entries === 1 ? "entry" : "entries"}, ${c.lever_leaves} lever leaves${c.no_go ? `, ${c.no_go} of them no-go` : ""}. Its ledger root ${c.work_root} sits at V${v}; its seal ${c.seal}.`,
    vertex: v, bits: b, hammingWeight: [...b].filter(x => x === "1").length, href: c.url,
    evidence: { status: "local implementation", observedAt: J.generated, sources: ["mages_city/site/chains.json"], note: `ledger root ${c.work_root}` },
  });
  edges.push({ source: id, target: "concept-poaw-chain", type: "instance_of" });
  edges.push({ source: id, target: "concept-mage-quest", type: "embodies" });
  if (vertexIds.has(`vertex-v${v}`)) edges.push({ source: id, target: `vertex-v${v}`, type: "anchors_to" });
}
const out = `// GENERATED by scripts/sync-chains.mjs from mages_city/site/chains.json (${J.generated}). Do not edit by hand.
import type { SpellwebNode, SpellwebEdge } from '../types/graph';

export const CHAIN_NODES: SpellwebNode[] = ${JSON.stringify(nodes, null, 1)} satisfies SpellwebNode[];

export const CHAIN_EDGES: SpellwebEdge[] = ${JSON.stringify(edges, null, 1)} satisfies SpellwebEdge[];
`;
fs.writeFileSync(path.join(ROOT, "src", "data", "chains.ts"), out);
console.log(`chains.ts: ${nodes.length - 2} chain nodes + two concepts, ${edges.length} edges (${edges.filter(e => e.type === "anchors_to").length} to existing vertex nodes)`);
